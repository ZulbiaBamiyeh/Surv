function mix(a: string, b: string, k: number) {
  const pa = parseInt(a.slice(1), 16);
  const pb = parseInt(b.slice(1), 16);
  const ch = (s: number) => Math.round(((pa >> s) & 255) * (1 - k) + ((pb >> s) & 255) * k);
  return `rgb(${ch(16)},${ch(8)},${ch(0)})`;
}

const cache = new Map<string, HTMLCanvasElement>();

/** An 11×11 canvas (glyph plus a 1px outline). */
export function glyph(name: string, color: string): HTMLCanvasElement {
  const key = name + color;
  const hit = cache.get(key);
  if (hit) return hit;
  const rows = G[name] ?? G.burst;
  const c = document.createElement("canvas");
  c.width = 11;
  c.height = 11;
  const x = c.getContext("2d")!;
  const filled = (i: number, j: number) => j >= 0 && j < 9 && i >= 0 && i < 9 && rows[j][i] !== ".";
  x.fillStyle = OUTLINE;
  for (let j = -1; j <= 9; j++)
    for (let i = -1; i <= 9; i++)
      if (!filled(i, j) && (filled(i + 1, j) || filled(i - 1, j) || filled(i, j + 1) || filled(i, j - 1))) x.fillRect(i + 1, j + 1, 1, 1);
  const pal: Record<string, string> = { "#": color, "+": mix(color, "#ffffff", 0.5), w: "#ffffff", o: mix(color, "#140d1c", 0.6) };
  rows.forEach((r, j) =>
    [...r].forEach((ch, i) => {
      if (ch === ".") return;
      x.fillStyle = pal[ch] ?? color;
      x.fillRect(i + 1, j + 1, 1, 1);
    }),
  );
  cache.set(key, c);
  return c;
}

export function glyphURL(name: string, color: string, scale = 3): string {
  const src = glyph(name, color);
  const c = document.createElement("canvas");
  c.width = src.width * scale;
  c.height = src.height * scale;
  const x = c.getContext("2d")!;
  x.imageSmoothingEnabled = false;
  x.drawImage(src, 0, 0, c.width, c.height);
  return c.toDataURL();
}

